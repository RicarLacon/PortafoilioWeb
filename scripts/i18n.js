const supportedLanguages = new Set(Object.keys(translations));
const languageStorageKey = "portfolio-language";
const cvFiles = Object.freeze({
    es: Object.freeze({
        path: "./frontend/CV/Imagen web ES.pdf",
        downloadName: "Ricardo-Murillo-CV-ES.pdf",
    }),
    en: Object.freeze({
        path: "./frontend/CV/Imagen web ENG.docx.pdf",
        downloadName: "Ricardo-Murillo-CV-EN.pdf",
    }),
});

const getStoredLanguage = () => {
    try {
        return localStorage.getItem(languageStorageKey);
    } catch {
        return null;
    }
};

const getInitialLanguage = () => {
    const storedLanguage = getStoredLanguage();

    if (supportedLanguages.has(storedLanguage)) {
        return storedLanguage;
    }

    return navigator.language.toLowerCase().startsWith("en") ? "en" : "es";
};

let currentLanguage = getInitialLanguage();

const translate = (key) =>
    translations[currentLanguage][key] ?? translations.es[key] ?? key;

const updateTranslatedAttributes = (selector, datasetKey, attributeName) => {
    document.querySelectorAll(selector).forEach((element) => {
        element.setAttribute(attributeName, translate(element.dataset[datasetKey]));
    });
};

const applyTranslations = () => {
    document.documentElement.lang = currentLanguage;
    document.title = translate("meta.title");

    const metaDescription = document.querySelector("#meta-description");
    metaDescription?.setAttribute("content", translate("meta.description"));

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        element.textContent = translate(element.dataset.i18n);
    });

    updateTranslatedAttributes(
        "[data-i18n-placeholder]",
        "i18nPlaceholder",
        "placeholder",
    );
    updateTranslatedAttributes("[data-i18n-aria-label]", "i18nAriaLabel", "aria-label");
    updateTranslatedAttributes("[data-i18n-title]", "i18nTitle", "title");
    updateTranslatedAttributes("[data-i18n-alt]", "i18nAlt", "alt");
    updateTranslatedAttributes("[data-i18n-value]", "i18nValue", "value");

    document.querySelectorAll("[data-i18n-cta]").forEach((element) => {
        element.dataset.cta = translate(element.dataset.i18nCta);
    });

    const languageToggle = document.querySelector("#language-toggle");
    if (languageToggle) {
        languageToggle.checked = currentLanguage === "en";
        languageToggle.setAttribute(
            "aria-label",
            translate(
                currentLanguage === "es"
                    ? "language.switchToEnglish"
                    : "language.switchToSpanish",
            ),
        );
    }

    const cvDownload = document.querySelector("#cv-download");
    if (cvDownload) {
        const selectedCv = cvFiles[currentLanguage] ?? cvFiles.es;
        cvDownload.href = encodeURI(selectedCv.path);
        cvDownload.download = selectedCv.downloadName;
    }

    const formStatus = document.querySelector("#form-status");
    if (formStatus?.dataset.statusKey) {
        formStatus.textContent = translate(formStatus.dataset.statusKey);
    }
};

const setLanguage = (language) => {
    if (!supportedLanguages.has(language) || language === currentLanguage) {
        return;
    }

    currentLanguage = language;

    try {
        localStorage.setItem(languageStorageKey, currentLanguage);
    } catch {
        // The site still works when storage is disabled by the browser.
    }

    applyTranslations();
    window.dispatchEvent(
        new CustomEvent("portfolio:languagechange", {
            detail: { language: currentLanguage },
        }),
    );
};

window.portfolioI18n = Object.freeze({
    getLanguage: () => currentLanguage,
    setLanguage,
    t: translate,
});

document.querySelector("#language-toggle")?.addEventListener("change", (event) => {
    setLanguage(event.currentTarget.checked ? "en" : "es");
});

applyTranslations();
